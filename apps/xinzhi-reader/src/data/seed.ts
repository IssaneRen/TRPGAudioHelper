function makeHighlight(
  articleId: string,
  blockIndex: number,
  phrase: string,
  color: HighlightColor,
  createdAt: string,
  note?: string,
): Highlight {
  const article = articles.find((item) => item.id === articleId)
  const block = article?.blocks[blockIndex]
  if (!block?.text) throw new Error(`Seed highlight block not found: ${articleId}/${blockIndex}`)
  const start = block.text.indexOf(phrase)
  if (start < 0) throw new Error(`Seed highlight phrase not found: ${phrase}`)
  return {
    id: `hl-${articleId}-${blockIndex}`,
    articleId,
    blockId: block.id,
    start,
    end: start + phrase.length,
    text: phrase,
    color,
    note,
    createdAt,
  }
}

